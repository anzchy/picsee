import Testing
import PicseeApplication

@Test func inspectorFocusTransitions() {
    var state = InspectorFocus()
    #expect(!state.isVisible)
    #expect(state.focus == .canvas)
    state.tab(reverse: false)
    #expect(state.focus == .canvas)
    state.updateFocus(.textInput)
    #expect(state.focus == .canvas)
    state.setVisible(true)
    #expect(state.isVisible)
    #expect(state.focus == .canvas)
    state.tab(reverse: true)
    #expect(state.focus == .canvas)
    state.tab(reverse: false)
    #expect(state.focus == .textInput)
    state.tab(reverse: true)
    #expect(state.focus == .canvas)
    state.tab(reverse: false)
    state.escape()
    #expect(state.focus == .canvas)
    #expect(state.isVisible)
    state.escape()
    #expect(state.focus == .canvas)
    state.updateFocus(.panel)
    #expect(state.focus == .panel)
    state.setVisible(true)
    #expect(state.focus == .panel)
    state.setVisible(false)
    #expect(state.focus == .canvas)
    #expect(!state.isVisible)
    state.setVisible(true)
    state.updateFocus(.textInput)
    state.setVisible(false)
    #expect(state.focus == .canvas)
    state.updateFocus(.canvas)
    #expect(state.focus == .canvas)
}
