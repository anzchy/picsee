import Testing
import PicseeApplication

@Test @MainActor func inspectorFocusTransitions() {
    let host = FakeSessionHost()
    let session = ViewerSession(host: host)
    #expect(!session.inspectorFocus.isVisible)
    #expect(session.inspectorFocus.focus == .canvas)
    session.tab(reverse: false)
    #expect(session.inspectorFocus.focus == .canvas)
    session.updateFocus(.textInput)
    #expect(session.inspectorFocus.focus == .canvas)
    session.setInspectorVisible(true)
    #expect(session.inspectorFocus.isVisible)
    #expect(session.inspectorFocus.focus == .canvas)
    session.tab(reverse: true)
    #expect(session.inspectorFocus.focus == .canvas)
    session.tab(reverse: false)
    #expect(session.inspectorFocus.focus == .textInput)
    #expect(host.focus == .textInput)
    session.tab(reverse: true)
    #expect(session.inspectorFocus.focus == .canvas)
    session.tab(reverse: false)
    CommandRouter().route(.escape, from: .key, to: session)
    #expect(session.inspectorFocus.focus == .canvas)
    #expect(session.inspectorFocus.isVisible)
    #expect(!CommandRouter().route(.escape, from: .key, to: session))
    #expect(session.inspectorFocus.focus == .canvas)
    session.updateFocus(.panel)
    #expect(session.inspectorFocus.focus == .panel)
    session.setInspectorVisible(true)
    #expect(session.inspectorFocus.focus == .panel)
    session.setInspectorVisible(false)
    #expect(session.inspectorFocus.focus == .canvas)
    #expect(!session.inspectorFocus.isVisible)
    session.setInspectorVisible(true)
    session.updateFocus(.textInput)
    session.setInspectorVisible(false)
    #expect(session.inspectorFocus.focus == .canvas)
    session.updateFocus(.canvas)
    #expect(session.inspectorFocus.focus == .canvas)
}
